/**
 * Generates supabase/migrations/0007_demo_seed.sql FROM the canonical demo
 * dataset (src/data/demoData.ts + demoStore.ts) via Vite SSR.
 *
 * Stage-2 collapse guarantee in mechanical form: one source of truth for demo
 * data. The SQL seeding the real tables is DERIVED from the same arrays the
 * app reads — the two worlds cannot drift. Re-run after changing demo data:
 *   node scripts/gen-demo-seed.mjs
 *
 * Deterministic UUIDs: every row id is md5(<demo string id>) as a uuid, so
 * re-runs are idempotent (ON CONFLICT DO NOTHING) and children can reference
 * parents generated in the same run.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true }, logLevel: 'error' });

function uid(demoId) {
  const hex = createHash('md5').update(demoId).digest('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`;
}
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const brandRef = (demoBrandId) =>
  `(select id from public.brands where legacy_demo_id = ${q(demoBrandId)})`;

try {
  const store = await server.ssrLoadModule('/src/data/demoStore.ts');
  const data = await server.ssrLoadModule('/src/data/demoData.ts');

  const out = [];
  out.push(`-- ── 0007: DEMO SEED — GENERATED FILE, DO NOT EDIT BY HAND ──────────
-- Generated by scripts/gen-demo-seed.mjs from src/data/demoData.ts.
-- Seeds the real tables with the exact rows demo mode uses, so live mode
-- and demo mode are the same data through the same tables.

alter table public.brands add column if not exists legacy_demo_id text unique;
`);

  // Brands
  out.push('-- ── Brands ──');
  data.ALL_DEMO_BRANDS.forEach((b, i) => {
    const gate = i % 3 === 0 ? 'cleared' : 'blocked';
    out.push(
      `insert into public.brands (id, legacy_demo_id, business_name, region, nation, email, signatory, category, fulfillment_track, onboarded, compliance_gate_status)\nvalues ('${uid(b.id)}', ${q(b.id)}, ${q(b.name)}, ${q(b.region)}, ${q(b.nation)}, ${q(b.email)}, ${q(b.signatory)}, ${q(b.category)}, ${q(b.track)}, true, '${gate}')\non conflict (id) do nothing;`
    );
  });

  // Products
  out.push('\n-- ── Products ──');
  for (const p of store.demoProducts ?? []) {
    out.push(
      `insert into public.products (id, brand_id, name, sku, barcode, image, ex_works_price, uk_retail_price, commodity_code, vat_status, hazmat, length_cm, width_cm, height_cm, weight_kg)\nvalues ('${uid(p.id)}', ${brandRef(p.brandId)}, ${q(p.name)}, ${q(p.sku)}, ${q(p.barcode ?? '')}, ${q(p.image ?? '')}, ${p.exWorksPrice}, ${p.ukRetailPrice}, ${q(p.commodityCode)}, ${q(p.vatStatus)}, ${p.hazmat}, ${p.length}, ${p.width}, ${p.height}, ${p.weight})\non conflict (id) do nothing;`
    );
  }

  // Purchase orders
  out.push('\n-- ── Purchase orders ──');
  for (const po of store.demoPurchaseOrders ?? []) {
    out.push(
      `insert into public.purchase_orders (id, brand_id, po_number, status, po_value, commission_rate, commission_amount, order_date, rejection_reason, line_items)\nvalues ('${uid(po.id)}', ${brandRef(po.brandId)}, ${q(po.poNumber)}, ${q(po.status)}, ${po.poValue}, ${po.commissionRate}, ${po.commissionAmount}, ${q(po.orderDate)}, ${po.rejectionReason ? q(po.rejectionReason) : 'null'}, ${q(JSON.stringify(po.lineItems))}::jsonb)\non conflict (id) do nothing;`
    );
  }

  // Shipments
  out.push('\n-- ── Shipments ──');
  (store.demoShipments ?? []).forEach((s, i) => {
    out.push(
      `insert into public.shipments (id, brand_id, reference, title, carrier, status, cbm, origin, destination, shipped_at)\nvalues ('${uid(s.id)}', ${brandRef(s.brandId)}, ${q(s.reference)}, ${q(s.title)}, ${q(s.carrier)}, ${q(s.status)}, 0, ${q(s.origin)}, ${q(s.destination)}, now() - interval '${i + 1} days')\non conflict (id) do nothing;`
    );
  });

  // Contracts
  out.push('\n-- ── Contracts ──');
  for (const c of store.demoContracts ?? []) {
    out.push(
      `insert into public.contracts (id, brand_id, type, status, commission_rate, monthly_fee, fulfillment_track, effective_date, renewal_date, signatories, version)\nvalues ('${uid(c.id)}', ${brandRef(c.brandId)}, ${q(c.type)}, ${q(c.status)}, ${c.commissionRate}, ${c.monthlyFee}, ${q(c.fulfillmentTrack)}, ${q(c.effectiveDate)}, ${q(c.renewalDate)}, ${q(JSON.stringify(c.signatories))}::jsonb, ${c.version})\non conflict (id) do nothing;`
    );
  }

  // Compliance documents
  out.push('\n-- ── Compliance documents ──');
  for (const d of store.demoComplianceDocs ?? []) {
    out.push(
      `insert into public.compliance_documents (id, brand_id, type, status, reviewed_by)\nvalues ('${uid(d.id)}', ${brandRef(d.brandId)}, ${q(d.type)}, ${q(d.status)}, ${d.reviewedBy ? q(d.reviewedBy) : 'null'})\non conflict (id) do nothing;`
    );
  }

  // Fulfillment scores
  out.push('\n-- ── Fulfillment scores ──');
  for (const s of store.demoFulfillmentScores ?? []) {
    out.push(
      `insert into public.fulfillment_scores (brand_id, trading_history_score, export_experience_score, scale_score, working_capital_score, category_risk_score, reliability_score, track, manual_override, override_reason)\nvalues (${brandRef(s.brandId)}, ${s.tradingHistoryScore}, ${s.exportExperienceScore}, ${s.scaleScore}, ${s.workingCapitalScore}, ${s.categoryRiskScore}, ${s.reliabilityScore}, ${q(s.track)}, ${s.manualOverride}, ${s.overrideReason ? q(s.overrideReason) : 'null'})\non conflict (brand_id) do nothing;`
    );
  }

  // Subscriptions
  out.push('\n-- ── Subscriptions ──');
  for (const s of store.demoSubscriptions ?? []) {
    out.push(
      `insert into public.subscriptions (id, brand_id, plan_tier, monthly_fee, stripe_subscription_id, status)\nvalues ('${uid(s.id)}', ${brandRef(s.brandId)}, ${q(s.planTier)}, ${s.monthlyFee}, null, ${q(s.status)})\non conflict (id) do nothing;`
    );
  }

  // Commissions
  out.push('\n-- ── Commissions ──');
  for (const c of store.demoCommissions ?? []) {
    out.push(
      `insert into public.commissions (id, brand_id, purchase_order_id, po_value, commission_rate, commission_amount, status)\nvalues ('${uid(c.id)}', ${brandRef(c.brandId)}, ${q(c.purchaseOrderId)}, ${c.poValue}, ${c.commissionRate}, ${c.commissionAmount}, ${q(c.status)})\non conflict (id) do nothing;`
    );
  }

  // Messages
  out.push('\n-- ── Messages ──');
  for (const m of store.demoMessages ?? []) {
    out.push(
      `insert into public.messages (id, brand_id, channel, direction, subject, body, sent_by, requires_human)\nvalues ('${uid(m.id)}', ${brandRef(m.brandId)}, ${q(m.channel)}, ${q(m.direction)}, ${m.subject ? q(m.subject) : 'null'}, ${q(m.body)}, ${q(m.sentBy)}, ${m.requiresHuman})\non conflict (id) do nothing;`
    );
  }

  // Shipping margin ledger
  out.push('\n-- ── Shipping margin ledger ──');
  for (const m of store.demoShippingMargins ?? []) {
    out.push(
      `insert into public.shipping_margins (id, shipment_id, brand_id, carrier, carrier_cost_price, brand_billed_price)\nvalues ('${uid(m.id)}', '${uid(m.shipmentId)}', ${brandRef(m.brandId)}, ${q(m.carrier)}, ${m.carrierCostPrice}, ${m.brandBilledPrice})\non conflict (id) do nothing;`
    );
  }

  writeFileSync('supabase/migrations/0007_demo_seed.sql', out.join('\n') + '\n');
  const counts = out.filter((l) => l.startsWith('insert')).length;
  console.log(`0007_demo_seed.sql written: ${counts} insert statements`);
} finally {
  await server.close();
}

